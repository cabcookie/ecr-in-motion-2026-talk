/**
 * Namen, die in den erzeugten Daten NICHT vorkommen dürfen — als Hashes.
 *
 * Warum nicht im Klartext: Eine Sperrliste verrät durch ihre Zusammensetzung,
 * was in der Vorlage stand. Eine Schokoladenkategorie, die ausgerechnet ein
 * Waschmittel verbietet, sagt mehr über ihre Quelle, als ihr lieb sein kann.
 *
 * Geprüft wird trotzdem vollständig: `marken-test.ts` zerlegt Sortiment und
 * Kulisse in Wörter und Wortpaare und schlägt an, wenn eines davon hier
 * getroffen wird. Der Klartext liegt bei der Vorlage, ausserhalb dieses Repos,
 * und bleibt dort nachlesbar.
 */

/** FNV-1a über den kleingeschriebenen Namen, Leerraum auf ein Leerzeichen normiert. */
export function kennung(text: string): number {
  let h = 0x811c9dc5;
  for (const zeichen of text.toLowerCase().split(/\s+/).join(' ')) {
    h ^= zeichen.charCodeAt(0);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h;
}

